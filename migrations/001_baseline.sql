-- 001_baseline.sql
--
-- Baseline schema for the mailadmin `mail` database, reconstructed from
-- internal/db/db.go, internal/db/models.go, and internal/db/apppw.go, the
-- single source of truth for the queries this file must support. This file
-- did not previously exist in version control; only 002_dns_provider.sql
-- (an ALTER TABLE against this schema) was checked in. It has already been
-- applied to the live `mail` database, so 001 must describe exactly the
-- state that predates it: in particular, `domain` here has NO dns_provider
-- column, 002 adds that with `ADD COLUMN IF NOT EXISTS`.
--
-- Column types/constraints below are derived from how each column is used in
-- internal/db, e.g.:
--   - `domain.dkim_selector` is read via COALESCE(dkim_selector, '') in
--     domainCols, so it is nullable.
--   - `mailbox` is looked up and upserted by (username, domain), ON CONFLICT
--     (username, domain) in CreateMailbox, so that pair is the primary key.
--   - `alias` is looked up and upserted by (source, destination), ON
--     CONFLICT (source, destination) in CreateAlias, so that pair is the
--     primary key.
--   - `app_password.id` scans into a Go `int`, not `int64` (models.go), so it
--     is `integer`, not `bigint`; it is upserted by (username, domain, label)
--    , ON CONFLICT (username, domain, label) in CreateAppPassword.
--   - `audit_log.id` scans into a Go `int64` (models.go), so it is `bigint`;
--     `ip` is read back via `host(ip)::text`, so its column type is `inet`.
--
-- Postfix and Dovecot read this schema directly (virtual_mailbox_maps,
-- virtual_alias_maps, SQL userdb/passdb) via a read-only role, see the
-- GRANT block at the end. The exact role name(s) and grant set were NOT
-- re-derived from a live \dp dump for this reconstruction (that requires
-- access to the running server), verify them against the live database
-- before relying on this file to rebuild permissions from scratch. See
-- docs/DISASTER-RECOVERY.md.

BEGIN;

-- ---- domain ----------------------------------------------------------
-- A virtual mail domain. dkim_selector is nullable: a freshly-added domain
-- may not have a selector set yet (db.go COALESCEs it to '' on read).
CREATE TABLE domain (
    name          text PRIMARY KEY,
    active        boolean     NOT NULL DEFAULT true,
    dkim_selector text,
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- ---- mailbox -----------------------------------------------------------
-- A virtual mailbox. (username, domain) is the natural key mailadmin always
-- looks up and upserts by (db.go: GetMailbox, CreateMailbox's ON CONFLICT).
CREATE TABLE mailbox (
    username    text        NOT NULL,
    domain      text        NOT NULL REFERENCES domain (name) ON DELETE CASCADE,
    password    text        NOT NULL, -- ARGON2ID modular-crypt hash (doveadm pw)
    quota_bytes bigint      NOT NULL DEFAULT 0,
    active      boolean     NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (username, domain)
);

-- Postfix's virtual_mailbox_maps / Dovecot's SQL userdb both filter by
-- domain; mailbox already carries it in the primary key, so lookups by
-- domain alone (ListMailboxes(domain)) use the PK's leading column.

-- ---- alias ---------------------------------------------------------------
-- Maps a source address (or "@domain" catch-all, see internal/cli/alias.go)
-- to a destination. (source, destination) is the natural key (db.go:
-- GetAlias, CreateAlias's ON CONFLICT, DeleteAlias).
CREATE TABLE alias (
    source      text    NOT NULL,
    destination text    NOT NULL,
    active      boolean NOT NULL DEFAULT true,
    PRIMARY KEY (source, destination)
);

-- ListAliases(domain) matches `source LIKE '%@'||$1 OR source='@'||$1`; an
-- index on source speeds the catch-all equality half and ORDER BY source.
CREATE INDEX alias_source_idx ON alias (source);

-- ---- app_password ----------------------------------------------------
-- Per-mailbox application password. id scans into a Go `int` (models.go), so
-- it is `integer` here, not `bigint`. Upserted by (username, domain, label)
-- (apppw.go: CreateAppPassword's ON CONFLICT).
CREATE TABLE app_password (
    id         integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   text        NOT NULL,
    domain     text        NOT NULL,
    label      text        NOT NULL,
    password   text        NOT NULL, -- ARGON2ID hash; plaintext is never stored
    active     boolean     NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_used  timestamptz,
    UNIQUE (username, domain, label),
    FOREIGN KEY (username, domain) REFERENCES mailbox (username, domain) ON DELETE CASCADE
);

CREATE INDEX app_password_mailbox_idx ON app_password (username, domain);

-- ---- audit_log -------------------------------------------------------
-- Append-only. id scans into a Go `int64` (models.go: AuditEntry.ID), so it
-- is `bigint`. ip is read back via `host(ip)::text` (db.go: ListAudit), so
-- its column type must support host(): `inet`.
CREATE TABLE audit_log (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts         timestamptz NOT NULL DEFAULT now(),
    actor      text        NOT NULL,
    action     text        NOT NULL,
    target     text        NOT NULL,
    before     jsonb,
    after      jsonb,
    ip         inet,
    user_agent text
);

-- ListAudit always orders by ts DESC LIMIT $1.
CREATE INDEX audit_log_ts_idx ON audit_log (ts DESC);

-- ---- roles / grants ------------------------------------------------------
-- mailadmin (this CLI) connects as the `mailadmin` role via a libpq service
-- file over the unix socket with peer auth (internal/db/db.go doc comment)
-- and needs full DML on every table above.
--
-- Postfix and Dovecot connect as their own read-only roles to resolve
-- virtual_mailbox_maps / virtual_alias_maps and the SQL userdb/passdb
-- (002_dns_provider.sql's comment: "postfix/dovecot select explicit columns,
-- and the table-level GRANT SELECT to postfix covers the new column").
--
-- The exact role names below (mailadmin/postfix/dovecot) match the actors
-- documented elsewhere in this repo, but this GRANT block was reconstructed,
-- not re-derived from a live `\dp` dump, confirm against the running server
-- (`psql -c '\dp'`) and adjust before trusting this file for a real rebuild.
-- See docs/DISASTER-RECOVERY.md, step "Recreate roles and grants".

-- CREATE ROLE mailadmin  LOGIN;  -- peer-authenticated as the mailadmin service account
-- CREATE ROLE postfix    LOGIN;
-- CREATE ROLE dovecot    LOGIN;

GRANT SELECT, INSERT, UPDATE, DELETE ON domain, mailbox, alias, app_password TO mailadmin;
GRANT SELECT, INSERT ON audit_log TO mailadmin;
GRANT USAGE ON SEQUENCE app_password_id_seq TO mailadmin;
GRANT USAGE ON SEQUENCE audit_log_id_seq TO mailadmin;

GRANT SELECT ON domain, mailbox, alias TO postfix;
GRANT SELECT ON domain, mailbox TO dovecot;

COMMIT;
