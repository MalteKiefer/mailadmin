package cli

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"

	"mailadmin/internal/dnsrepo"
	"mailadmin/internal/mail"
	"mailadmin/internal/valid"
)

func newDNSSyncCmd(app *App) *cobra.Command {
	var del, withMTASTS bool
	cmd := &cobra.Command{
		Use:   "sync <domain>",
		Short: "Write the mail record-set into dnsconfig.js (dns.config_repo) as a pull request",
		Long: "Writes the desired mail records of the domain into the mailadmin block of its\n" +
			"D(...) call in dnsconfig.js, on a new branch, committed and pushed as a pull\n" +
			"request. Nothing is merged here.\n\n" +
			"Without --delete the sync stops when the zone holds mail records outside the\n" +
			"mailadmin block (MX, SPF, DMARC, TLS-RPT, DKIM, SRV, autoconfig, autodiscover,\n" +
			"mta-sts, mail host, TLSA). With --delete those records are removed in the same\n" +
			"pull request and replaced by the mail record-set. Web records are kept.\n\n" +
			"The TLSA record goes into the zone of the mail host, so sync of that zone\n" +
			"includes it.",
		Args: cobra.ExactArgs(1),
		RunE: func(c *cobra.Command, args []string) error {
			return app.dnsSync(c, args[0], del, withMTASTS)
		},
	}
	cmd.Flags().BoolVar(&del, "delete", false, "remove the existing mail records outside the mailadmin block and replace them")
	cmd.Flags().BoolVar(&withMTASTS, "with-mta-sts", false, "include the MTA-STS records")
	return cmd
}

// dnsSync builds the desired mail record-set of domain and proposes it in dnsconfig.js.
func (a *App) dnsSync(cmd *cobra.Command, rawDomain string, del, withMTASTS bool) error {
	cfg, _, err := a.Config()
	if err != nil {
		return err
	}
	if cfg.DNS.ConfigRepo == "" {
		return fmt.Errorf("%w: dns.config_repo is not set", ErrUsage)
	}
	domain, err := valid.Domain(rawDomain)
	if err != nil {
		return fmt.Errorf("%w: %w", ErrUsage, err)
	}
	r, err := a.Renderer()
	if err != nil {
		return err
	}
	database, err := a.openDB(cmd, cfg)
	if err != nil {
		return err
	}
	dom, err := getDomain(ctx(cmd), database, domain)
	if err != nil {
		return err
	}
	mgr := mail.New(a.sysRunner(), cfg.Mail.DKIMDir, cfg.Mail.Hostname, cfg.Server.IPv4, cfg.Server.IPv6, cfg.Mail.DNSTTL)
	key, err := mgr.ReadDKIM(domain, dom.DKIMSelector)
	if err != nil {
		return fmt.Errorf("dns sync %s: %w", domain, err)
	}
	recs := mgr.DesiredRecords(domain, dom.DKIMSelector, key.PublicKey, withMTASTS)
	if h := strings.ToLower(strings.TrimSuffix(cfg.Mail.Hostname, ".")); h == domain || strings.HasSuffix(h, "."+domain) {
		rec, _, derr := a.daneRecord(ctx(cmd), cfg, domain)
		if derr != nil {
			return fmt.Errorf("dns sync %s: TLSA: %w", domain, derr)
		}
		recs = append(recs, rec)
	}
	lines := make([]string, 0, len(recs))
	for _, rec := range recs {
		line, rerr := dnsrepo.RenderRecord(rec)
		if rerr != nil {
			return fmt.Errorf("dns sync %s: %w", domain, rerr)
		}
		lines = append(lines, line)
	}

	repo := dnsrepo.Repo{Dir: cfg.DNS.ConfigRepo}
	edit := func(src string) (string, error) {
		out, removed, err := dnsrepo.SetManaged(src, domain, lines, dnsrepo.MailScope)
		if err != nil {
			return "", err
		}
		if len(removed) > 0 && !del {
			return "", fmt.Errorf("%w: %d mail record(s) outside the mailadmin block, rerun with --delete to replace them:\n  %s",
				ErrUsage, len(removed), strings.Join(removed, "\n  "))
		}
		return out, nil
	}

	if a.flags.dryRun {
		data, err := os.ReadFile(filepath.Join(repo.Dir, "dnsconfig.js")) // #nosec G304 -- dnsconfig.js in the configured repository
		if err != nil {
			return err
		}
		out, err := edit(string(data))
		if err != nil {
			return err
		}
		r.Message("dry-run: %d record(s) in the mailadmin block of %s", len(lines), domain)
		if out == string(data) {
			r.Message("dry-run: dnsconfig.js already current")
		}
		return nil
	}
	if err := a.confirm(fmt.Sprintf("Propose the mail record-set of %s in %s as a pull request?", domain, cfg.DNS.ConfigRepo)); err != nil {
		return err
	}
	title := "dns: mail records for " + domain
	body := fmt.Sprintf("Generated by mailadmin dns sync (%d records).", len(lines))
	if del {
		body += " Existing mail records outside the mailadmin block were removed (--delete)."
	}
	prop, err := repo.ProposeEdit(ctx(cmd), "mailadmin/sync-"+domain, title, body, edit)
	if errors.Is(err, dnsrepo.ErrUnchanged) {
		r.Message("dnsconfig.js already holds the mail records of %s", domain)
		return nil
	}
	if err != nil {
		return fmt.Errorf("dns sync %s: %w", domain, err)
	}
	r.Message("pull request for %s: %s", domain, prop.URL)
	return nil
}
