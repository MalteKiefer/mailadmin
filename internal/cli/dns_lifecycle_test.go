// --- drift-check argument handling ---

func TestValidateDriftCheckArgs(t *testing.T) {
	cases := []struct {
		name    string
		domain  string
		all     bool
		wantErr bool
	}{
		{"domain only", "example.com", false, false},
		{"all only", "", true, false},
		{"neither", "", false, true},
		{"both", "example.com", true, true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			err := validateDriftCheckArgs(c.domain, c.all)
			if c.wantErr && err == nil {
				t.Fatalf("validateDriftCheckArgs(%q, %v) = nil, want error", c.domain, c.all)
			}
			if !c.wantErr && err != nil {
				t.Fatalf("validateDriftCheckArgs(%q, %v) = %v, want nil", c.domain, c.all, err)
			}
			if err != nil && !errors.Is(err, ErrUsage) {
				t.Errorf("error %v does not wrap ErrUsage", err)
			}
		})
	}
}

// --- DKIM rotation: selector resolution ---

func TestResolveRotateSelector_Explicit(t *testing.T) {
	got, err := resolveRotateSelector("mail2026", "mail2027")
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if got != "mail2027" {
		t.Errorf("got %q, want mail2027", got)
	}
}

func TestResolveRotateSelector_AutoGenerated(t *testing.T) {
	got, err := resolveRotateSelector("mail2026", "")
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if !strings.HasPrefix(got, "mail2026-") {
		t.Errorf("got %q, want a mail2026-<date> selector", got)
	}
	if got == "mail2026" {
		t.Errorf("auto-generated selector must differ from current")
	}
}

func TestResolveRotateSelector_SameAsCurrent(t *testing.T) {
	_, err := resolveRotateSelector("mail2026", "mail2026")
	if err == nil {
		t.Fatal("expected error when new selector equals current")
	}
	if !errors.Is(err, ErrUsage) {
		t.Errorf("error %v does not wrap ErrUsage", err)
	}
}

func TestResolveRotateSelector_InvalidSelector(t *testing.T) {
	_, err := resolveRotateSelector("mail2026", "not a valid selector!!")
	if err == nil {
		t.Fatal("expected error for an invalid selector")
	}
	if !errors.Is(err, ErrUsage) {
		t.Errorf("error %v does not wrap ErrUsage", err)
	}
}

func TestAutoRotateSelector_Deterministic(t *testing.T) {
	a := autoRotateSelector("mail2026")
	b := autoRotateSelector("mail2026")
	if a != b {
		t.Errorf("autoRotateSelector should be deterministic within the same day: %q != %q", a, b)
	}
}

// --- old DKIM DNS record cleanup (dkim-rotate-finish --remove-old) ---

// fakeDKIMProvider is a minimal in-memory dnsprovider.Provider for testing
// removeDKIMDNSRecord without a network.
type fakeDKIMProvider struct {
	name    string
	records []dnsprovider.Record
	removed []string
}

func (f *fakeDKIMProvider) Name() string { return f.name }
func (f *fakeDKIMProvider) ListRecords(context.Context, string) ([]dnsprovider.Record, error) {
	return f.records, nil
}
func (f *fakeDKIMProvider) AddRecord(context.Context, string, dnsprovider.Record) error { return nil }
func (f *fakeDKIMProvider) EditRecord(context.Context, string, dnsprovider.Record) error {
	return nil
}
func (f *fakeDKIMProvider) RemoveRecord(_ context.Context, _ string, id string) error {
	f.removed = append(f.removed, id)
	return nil
}

func TestRemoveDKIMDNSRecord_RemovesMatch(t *testing.T) {
	p := &fakeDKIMProvider{
		name: "fake",
		records: []dnsprovider.Record{
			{ID: "1", Type: "TXT", Name: "mail2026._domainkey", Content: "v=DKIM1; p=abc"},
			{ID: "2", Type: "TXT", Name: "_dmarc", Content: "v=DMARC1; p=reject"},
		},
	}
	if err := removeDKIMDNSRecord(context.Background(), p, "example.com", "mail2026"); err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(p.removed) != 1 || p.removed[0] != "1" {
		t.Errorf("removed = %v, want [1]", p.removed)
	}
}

func TestRemoveDKIMDNSRecord_NoMatch(t *testing.T) {
	p := &fakeDKIMProvider{
		name: "fake",
		records: []dnsprovider.Record{
			{ID: "2", Type: "TXT", Name: "_dmarc", Content: "v=DMARC1; p=reject"},
		},
	}
	if err := removeDKIMDNSRecord(context.Background(), p, "example.com", "mail2026"); err == nil {
		t.Fatal("expected an error when no matching record exists")
	}
	if len(p.removed) != 0 {
		t.Errorf("removed = %v, want none", p.removed)
	}
}

func TestRemoveDKIMDNSRecord_IgnoresEmptyID(t *testing.T) {
	p := &fakeDKIMProvider{
		name: "fake",
		records: []dnsprovider.Record{
			{ID: "", Type: "TXT", Name: "mail2026._domainkey", Content: "v=DKIM1; p=abc"},
		},
	}
	if err := removeDKIMDNSRecord(context.Background(), p, "example.com", "mail2026"); err == nil {
		t.Fatal("expected an error when the matching record has no provider ID")
	}
}
